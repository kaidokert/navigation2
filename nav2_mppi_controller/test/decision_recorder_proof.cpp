class Probe : public mppi::Optimizer
{
public:
  void seed()
  {
    xt::random::seed(81471); reset(); fallback(false);
    control_sequence_.vx.fill(.15f); control_sequence_.wz.fill(0);
    control_history_.fill({.15f,0,0});
  }
  void stage(const geometry_msgs::msg::PoseStamped & pose, const nav_msgs::msg::Path & plan,
    const std::string & kind)
  {
    geometry_msgs::msg::Twist speed;
    prepare(pose,speed,plan,plan.poses.back().pose,nullptr);
    control_sequence_.vx.fill(0); control_sequence_.wz.fill(0); control_history_.fill({0,0,0});
    for (size_t b=0;b<settings_.batch_size;++b) {
      for (size_t j=0;j<settings_.time_steps;++j) {
        float vx = kind=="suppression" ? .10f : (b%2 ? -.10f : .10f);
        if (kind=="critic_stop" && b==0) {vx=0;}
        state_.cvx(b,j)=vx; state_.cvy(b,j)=0;state_.cwz(b,j)=0;
        state_.vx(b,j)=vx;state_.vy(b,j)=0;state_.wz(b,j)=0;
      }
    }
    // Explicit injected candidate bank for isolated scoring/update/extraction proof.
    // No claim this bank was generated by random sampling or the physical predictor.
    integrateStateVelocities(generated_trajectories_,state_);
    critic_manager_.evalTrajectoriesScores(critics_data_);
    if (critics_data_.fail_flag) {return;}
    if (kind=="suppression") {setSpeedLimit(.005,false);}
    updateControlSequence(false);
  }
  bool failed() const {return critics_data_.fail_flag;}
  bool fallbackNow() {return fallback(critics_data_.fail_flag);}
  void scoreAgain()
  {costs_.fill(0);critics_data_.fail_flag=false;critic_manager_.evalTrajectoriesScores(critics_data_);}
  geometry_msgs::msg::TwistStamped finish(const builtin_interfaces::msg::Time & stamp)
  {
    rec::observe("before_smoothing",[&]{return rec::Json{{"control",rec::sequence(control_sequence_)},{"history",rec::history(control_history_)}};});
    smoothControlSequence();
    rec::observe("after_smoothing",[&]{return rec::Json{{"control",rec::sequence(control_sequence_)},{"history",rec::history(control_history_)}};});
    auto command=getControlFromSequenceAsTwist(stamp);
    return command;
  }
  void updateAgain() {updateControlSequence(false);}
};
struct Scene
{
  std::shared_ptr<nav2_costmap_2d::Costmap2DROS> map;
  rclcpp_lifecycle::LifecycleNode::SharedPtr node;
  std::unique_ptr<mppi::ParametersHandler> params;
  Probe optimizer;
  geometry_msgs::msg::PoseStamped pose;
  nav_msgs::msg::Path path;
  Scene(bool lateral=false,int batch=64,int steps=16,int iterations=2)
  {
    TestCostmapSettings ms;map=getDummyCostmapRos(ms);
    TestOptimizerSettings os{batch,steps,iterations,1.7,"Ackermann",true};
    auto options=getOptimizerOptions(os,{"PathFollowCritic","ObstaclesCritic"});
    auto overrides=options.parameter_overrides();
    overrides.emplace_back("controller_frequency",20.0);
    overrides.emplace_back("dummy.model_dt",.05);
    overrides.emplace_back("dummy.regenerate_noises",false);
    overrides.emplace_back("dummy.condition_control_on_path_direction",false);
    overrides.emplace_back("dummy.PathFollowCritic.threshold_to_consider",.001);
    overrides.emplace_back("dummy.PathFollowCritic.cost_weight",500.0);
    overrides.emplace_back("dummy.ObstaclesCritic.consider_footprint",true);
    options.parameter_overrides(overrides);node=getDummyNode(options);
    params=std::make_unique<mppi::ParametersHandler>(node);
    xt::random::seed(81471);optimizer.initialize(node,"dummy",map,params.get());optimizer.seed();
    pose.header.frame_id="map";pose.header.stamp.sec=1;pose.header.stamp.nanosec=0;
    pose.pose.position.x=2;pose.pose.position.y=2;pose.pose.orientation.w=1;
    path.header=pose.header;
    for(int i=0;i<20;++i){auto p=pose;if(lateral){p.pose.position.y+=.05*i;}else{p.pose.position.x+=.05*i;}path.poses.push_back(p);}
    optimizer.setRealPathPointCount(path.poses.size());
  }
  ~Scene(){optimizer.shutdown();}
  rec::Json manifest(const std::string & name) const
  {
    rec::Json parameters=rec::Json::object();
    for(const auto & n:node->list_parameters({},10).names){parameters[n]=node->get_parameter(n).value_to_string();}
    rec::Json loaded=rec::Json::array();std::ifstream maps("/proc/self/maps");std::string line;
    while(std::getline(maps,line)){if(line.find("libmppi_controller.so")!=std::string::npos||line.find("libmppi_critics.so")!=std::string::npos){loaded.push_back(line);}}
    return {{"loaded_mppi_mappings",loaded},{"run_id",name},{"goal_uuid","native-fixture-goal"},{"native_baseline","7adf498bbe5db1d68cfe7d109b5b42432004478c"},
      {"parameters",parameters},{"plant","none: native deterministic fixture"},
      {"frame_chain",{{"map_to_controller_base","identity fixture, not a live TF lookup"}}},
      {"candidate_scope",(name=="healthy" || name=="smoothing" || name=="benchmark") ? "production generator/predictor" : "explicitly injected bank; production scoring/update/extraction"}};
  }
};
void save(const std::string & name,rec::Recorder & recorder,const geometry_msgs::msg::TwistStamped & command)
{
  auto out=std::filesystem::path(std::getenv("RECORDER_PROOF_OUTPUT"));
  std::filesystem::create_directories(out);recorder.trigger("manual");recorder.writeExclusive((out/(name+".trace.json")).string());
  std::ofstream f(out/(name+".witness.json"));
  f<<rec::Json{{"vx",command.twist.linear.x},{"vy",command.twist.linear.y},{"wz",command.twist.angular.z},
    {"source","separate native function return, not re-read from trace"}}.dump(2);
}

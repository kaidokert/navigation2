TEST(DecisionRecorderProof,ActualRejectionFallbackAndRecovery)
{
  Scene s;rec::Recorder recorder(s.manifest("rejection_retry"));geometry_msgs::msg::TwistStamped command;
  {
    rec::Session recording(recorder);rec::Invocation invocation(1000000000);
    auto * map=s.map->getCostmap();
    std::fill(map->getCharMap(),map->getCharMap()+map->getSizeInCellsX()*map->getSizeInCellsY(),254);
    s.optimizer.stage(s.pose,s.path,"rejection");ASSERT_TRUE(s.optimizer.failed());
    ASSERT_TRUE(s.optimizer.fallbackNow());++recorder.retry;
    // Explicit controlled recovery intervention: free the map between score banks.
    std::fill(map->getCharMap(),map->getCharMap()+map->getSizeInCellsX()*map->getSizeInCellsY(),0);
    rec::observe("fixture_intervention",[]{return rec::Json{{"operation","clear exact grid between failed retry and recovery"}};});
    s.optimizer.stage(s.pose,s.path,"recovery");ASSERT_FALSE(s.optimizer.failed());
    command=s.optimizer.finish(s.pose.header.stamp);
  }
  save("rejection_retry",recorder,command);
}

